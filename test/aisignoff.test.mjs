import assert from 'node:assert/strict';
import { test } from 'node:test';
import { LEVELS, describe, problems } from '../src/lib/aisignoff.ts';

test('the builder has four levels per scale, named as in the AI policy', () => {
  assert.deepEqual(LEVELS.generation.map((l) => l.level), ['G0', 'G1', 'G2', 'G3']);
  assert.deepEqual(LEVELS.human.map((l) => l.level), ['H0', 'H1', 'H2', 'H3']);
  assert.deepEqual(LEVELS.ai.map((l) => l.level), ['A0', 'A1', 'A2', 'A3']);
});

test('the builder applies the two rules of the policy', () => {
  assert.equal(problems({ generation: 2, human: 0, ai: 0 }).length, 1); // AI-written needs at least A1
  assert.equal(problems({ generation: 0, human: 2, ai: 1 }).length, 1); // G0 is never A1
  assert.equal(problems({ generation: 0, human: 2, ai: 0 }).length, 0);
  assert.equal(problems({ generation: 3, human: 1, ai: 1 }).length, 0);
});

test('the builder writes the SIGNOFF.toml keys each level needs', () => {
  const human = describe({ generation: 0, human: 2, ai: 0 });
  assert.equal(human.label, 'G0 · H2 · A0');
  assert.doesNotMatch(human.toml, /Assisted-by|AI-Reviewed-by/);
  assert.match(human.toml, /Reviewed-by = "Jane Doe"/);
  const ai = describe({ generation: 2, human: 2, ai: 2 });
  assert.equal(ai.sentence, 'Generated by AI under human direction, reviewed line by line by a human, and reviewed by a new AI session.');
  assert.match(ai.toml, /Assisted-by = /);
  assert.match(ai.toml, /AI-Reviewed-by = ".*new session"/);
  assert.match(ai.command, /^aisignoff annotate src\/ -g G2 -H H2 -a A2/);
});

test('the builder writes the lines for a pull request description and the review gap', () => {
  const d = describe({ generation: 3, human: 1, ai: 1 });
  assert.equal(d.gap, 2);
  assert.equal(describe({ generation: 0, human: 2, ai: 0 }).gap, 0);
  assert.deepEqual(d.lines.split('\n'), [
    'AI-Generation: G3',
    'Human-Review: H1',
    'AI-Review: A1',
    'Assisted-by: Claude Opus 5.5 (Anthropic)',
    'Reviewed-by: Jane Doe',
    'AI-Reviewed-by: Claude Opus 5.5 (Anthropic), self-check by the generating session',
  ]);
  assert.doesNotMatch(describe({ generation: 0, human: 2, ai: 0 }).lines, /Assisted-by|AI-Reviewed-by/);
});
