// The levels of the group's AI policy and the rules aisignoff checks, for the declaration builder on
// /explore/ai-declarations/. Sources: CONTRIBUTING.md#ai-assisted-contributions in industrial-mathematics-group/.github
// and the documentation of industrial-mathematics-group/aisignoff.

export type Axis = 'generation' | 'human' | 'ai';

export const LEVELS: Record<Axis, { level: string; name: string; meaning: string; phrase: string }[]> = {
  generation: [
    { level: 'G0', name: 'Human', meaning: 'Written by a human. Spell-checking and single-line autocomplete don’t count as AI use.', phrase: 'written by a human' },
    { level: 'G1', name: 'AI-assisted', meaning: 'A human wrote the change; AI suggested or edited parts of it.', phrase: 'written by a human with AI assistance' },
    { level: 'G2', name: 'AI-generated', meaning: 'AI wrote substantial parts; a human directed the work and edited the result.', phrase: 'generated by AI under human direction' },
    { level: 'G3', name: 'AI-autonomous', meaning: 'An agent produced the change largely end to end, with little human editing.', phrase: 'produced by an AI agent largely end to end' },
  ],
  human: [
    { level: 'H0', name: 'Plausibility check', meaning: 'Looked at the result as a whole: it does what was asked, runs, and the output is plausible.', phrase: 'checked for plausibility by a human' },
    { level: 'H1', name: 'Tested', meaning: 'Ran the tests or reproduced the key results, and read the important parts.', phrase: 'tested by a human' },
    { level: 'H2', name: 'Reviewed', meaning: 'Read every changed line, understands it, and checked edge cases.', phrase: 'reviewed line by line by a human' },
    { level: 'H3', name: 'Validated', meaning: 'H2, plus an independent check: new tests, a reference solution, or a second person.', phrase: 'reviewed and independently validated by a human' },
  ],
  ai: [
    { level: 'A0', name: 'None', meaning: 'No AI reviewed the change.', phrase: 'not reviewed by an AI' },
    { level: 'A1', name: 'Self-check', meaning: 'The AI session that wrote the change ran the tests and checked its own output.', phrase: 'self-checked by the AI session that wrote it' },
    { level: 'A2', name: 'New session', meaning: 'A new session, without the generating conversation, reviewed the final change and ran the tests.', phrase: 'reviewed by a new AI session' },
    { level: 'A3', name: 'Different model, extensive', meaning: 'A different model of similar or higher capability reviewed or benchmarked it extensively.', phrase: 'reviewed extensively by a different AI model' },
  ],
};

export interface Declaration {
  generation: number;
  human: number;
  ai: number;
}

export interface Described {
  label: string;
  sentence: string;
  problems: string[];
  // "Key: value" lines for a pull request description or a commit message ([history] in SIGNOFF.toml).
  lines: string;
  toml: string;
  command: string;
  // The review gap of aisignoff's folder report: generation level minus human review level, never below 0.
  gap: number;
}

const level = (axis: Axis, i: number) => LEVELS[axis][i].level;

// The rules of the policy that depend only on the levels (aisignoff lint checks the same).
export function problems({ generation, ai }: Declaration): string[] {
  const out: string[] = [];
  if (generation >= 1 && ai === 0) out.push('AI-written content must at least be self-checked: G1–G3 need A1 or higher.');
  if (generation === 0 && ai === 1) out.push('G0 is never A1: human-written content has no generating session, so any AI review of it counts as A2 or A3.');
  return out;
}

export function describe(d: Declaration, path = 'src/**'): Described {
  const g = level('generation', d.generation);
  const h = level('human', d.human);
  const a = level('ai', d.ai);
  const sentence = `${capitalise(LEVELS.generation[d.generation].phrase)}, ${LEVELS.human[d.human].phrase}, and ${LEVELS.ai[d.ai].phrase}.`;
  const assisted = d.generation > 0 ? 'Claude Opus 5.5 (Anthropic)' : null;
  const aiReviewer =
    ['', 'Claude Opus 5.5 (Anthropic), self-check by the generating session', 'Claude Opus 5.5 (Anthropic), new session', 'GPT-5 (OpenAI), benchmark against reference solutions'][d.ai] || null;
  const lines = [
    `AI-Generation: ${g}`,
    `Human-Review: ${h}`,
    `AI-Review: ${a}`,
    ...(assisted ? [`Assisted-by: ${assisted}`] : []),
    'Reviewed-by: Jane Doe',
    ...(aiReviewer ? [`AI-Reviewed-by: ${aiReviewer}`] : []),
  ].join('\n');
  const toml = [
    '[[annotations]]',
    `path = "${path}"`,
    `AI-Generation = "${g}"`,
    `Human-Review = "${h}"`,
    `AI-Review = "${a}"`,
    ...(assisted ? [`Assisted-by = "${assisted}"`] : []),
    ...(aiReviewer ? [`AI-Reviewed-by = "${aiReviewer}"`] : []),
    'Reviewed-by = "Jane Doe"',
  ].join('\n');
  const folder = path.replace(/\/\*\*$/, '/');
  const command = [
    `aisignoff annotate ${folder} -g ${g} -H ${h} -a ${a}`,
    ...(assisted ? [`    --assisted-by "${assisted}"`] : []),
    ...(aiReviewer ? [`    --ai-reviewed-by "${aiReviewer}"`] : []),
    '    --reviewed-by "Jane Doe"',
  ].join(' \\\n');
  return { label: `${g} · ${h} · ${a}`, sentence, problems: problems(d), lines, toml, command, gap: Math.max(0, d.generation - d.human) };
}

const capitalise = (text: string) => text[0].toUpperCase() + text.slice(1);
